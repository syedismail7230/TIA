function getMatchedLogo(category, index) {
  let list = LOGO_MAP.COMMERCE_RETAIL;
  const catLower = category.toLowerCase();
  
  if (catLower.includes('audio') || catLower.includes('music') || catLower.includes('sound')) {
    list = LOGO_MAP.AUDIO;
  } else if (catLower.includes('mobile') || catLower.includes('camera') || catLower.includes('smartphone') || catLower.includes('photography')) {
    list = LOGO_MAP.TECH_FLAGSHIP;
  } else if (catLower.includes('fitness') || catLower.includes('sport') || catLower.includes('gym') || catLower.includes('yoga') || catLower.includes('running') || catLower.includes('workout')) {
    list = LOGO_MAP.SPORTS_FITNESS;
  } else if (catLower.includes('streetwear') || catLower.includes('fashion') || catLower.includes('apparel') || catLower.includes('saree') || catLower.includes('denim') || catLower.includes('clothing') || catLower.includes('menswear')) {
    list = LOGO_MAP.FASHION_APPAREL;
  } else if (catLower.includes('automobile') || catLower.includes('ev') || catLower.includes('scooter') || catLower.includes('mobility') || catLower.includes('services')) {
    list = LOGO_MAP.AUTOMOBILE_MOBILITY;
  } else if (catLower.includes('beverage') || catLower.includes('coffee') || catLower.includes('tea') || catLower.includes('drink') || catLower.includes('chai') || catLower.includes('juice') || catLower.includes('stamina')) {
    list = LOGO_MAP.BEVERAGES_COFFEE;
  } else if (catLower.includes('finance') || catLower.includes('saving') || catLower.includes('gold') || catLower.includes('crypto') || catLower.includes('stock')) {
    list = LOGO_MAP.FINANCE_FINTECH;
  } else if (catLower.includes('gaming') || catLower.includes('esports') || catLower.includes('twitch')) {
    list = LOGO_MAP.GAMING_STREAMING;
  } else if (catLower.includes('design') || catLower.includes('beauty') || catLower.includes('cosmetics') || catLower.includes('skincare') || catLower.includes('fragrance')) {
    list = LOGO_MAP.DESIGN_CREATIVE;
  } else if (catLower.includes('travel') || catLower.includes('hotel') || catLower.includes('luggage') || catLower.includes('road trip')) {
    list = LOGO_MAP.TRAVEL_HOSPITALITY;
  } else if (catLower.includes('parenting') || catLower.includes('education') || catLower.includes('kids')) {
    list = LOGO_MAP.EDUCATION;
  } else if (catLower.includes('software') || catLower.includes('coding') || catLower.includes('ai') || catLower.includes('technology')) {
    list = LOGO_MAP.TECH_SOFTWARE;
  } else if (catLower.includes('entertainment') || catLower.includes('movie') || catLower.includes('film')) {
    list = LOGO_MAP.ENTERTAINMENT;
  }
  
  return list[index % list.length];
}

